"""Generate the dependency policy from one manifest.

UniVRM is bundled under Editor/Vendor/UniVRM (Tools/vendor-univrm.py), so no
assembly is gated on the project's own UniVRM and the manifest does not list it.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def version_tuple(version):
    """Numeric X.Y.Z without leading zeros; pre-releases and build metadata are rejected."""
    assert re.fullmatch(r'(0|[1-9][0-9]{0,8})\.(0|[1-9][0-9]{0,8})\.(0|[1-9][0-9]{0,8})', version), version
    return tuple(map(int, version.split('.')))


def outputs(root=ROOT):
    data = json.loads((root / 'Compatibility/dependencies.json').read_text(encoding='utf-8'))
    assert data['format'] == 1
    assert 'uniVrm' not in data, 'UniVRM is bundled, not a dependency'
    lil = data['lilToon']
    # `version` is the catalogue every export conforms to; `verified` is the range
    # of lilToon releases whose shader structure was checked to match that
    # catalogue (Tools/check-liltoon-structure.py). Nothing in the Exporter stops
    # on it, so it is not generated into the policy.
    assert lil['version'] == '2.3.4' and (lil['schemaMajor'], lil['schemaMinor']) == (2, 0)
    verified = lil['verified']
    assert set(verified) == {'minimum', 'maximum'}
    minimum, maximum, catalogue_version = (version_tuple(verified['minimum']), version_tuple(verified['maximum']),
                                           version_tuple(lil['version']))
    assert minimum <= catalogue_version <= maximum
    assert re.fullmatch(r'[a-f0-9]{40}', lil['commit'])
    catalogue = (root / 'Formats/Runtime/LilToon234Catalogue.cs').read_text(encoding='utf-8')
    assert 'Version = "' + lil['version'] + '"' in catalogue
    assert 'Commit = "' + lil['commit'] + '"' in catalogue
    authoring = data['authoring']
    # Half-open VRChat SDK range in which VRCAnimatorPlayAudio may be omitted
    # from an expression capture copy.
    assert version_tuple(authoring['vrchatSdkMinimum']) < version_tuple(authoring['vrchatSdkBelow'])
    # Half-open Modular Avatar range whose preview API the appearance freeze
    # reflects; the verified reference release must lie inside it.
    assert (version_tuple(authoring['modularAvatarMinimum']) <= version_tuple(authoring['modularAvatarReference'])
            < version_tuple(authoring['modularAvatarBelow']))
    values = {
        'LilToonVersion': lil['version'], 'LilToonCommit': lil['commit'],
        'NdmfMinimum': authoring['ndmfMinimum'], 'NdmfReference': authoring['ndmfReference'],
        'ModularAvatarReference': authoring['modularAvatarReference'],
        'VrchatSdkMinimum': authoring['vrchatSdkMinimum'], 'VrchatSdkBelow': authoring['vrchatSdkBelow'],
        'ModularAvatarMinimum': authoring['modularAvatarMinimum'], 'ModularAvatarBelow': authoring['modularAvatarBelow'],
    }
    text = '// Generated by Tools/generate-compatibility.py. Do not edit.\n'
    text += 'namespace VRVlog.LilToonExporter.Compatibility\n{\n    public static partial class DependencyPolicy\n    {\n'
    for key, value in values.items():
        text += '        public const string ' + key + ' = ' + json.dumps(value) + ';\n'
    text += '        public const int NdmfMajor = ' + str(authoring['ndmfMajor']) + ';\n'
    text += '    }\n}\n'
    result = {'Editor/Compatibility/DependencyPolicy.Generated.cs': text}
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, content in outputs().items():
        path = ROOT / name
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
        elif not path.exists() or path.read_text(encoding='utf-8') != content:
            stale.append(name)
    if stale:
        raise SystemExit('Run python3 Tools/generate-compatibility.py --write: ' + ', '.join(stale))
    print('Dependency policy matches the compatibility manifest.')


if __name__ == '__main__':
    main()
